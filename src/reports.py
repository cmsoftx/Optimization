"""Generated Markdown reports. Every number is read from computed tables."""
from __future__ import annotations

import pandas as pd

from .config import get_path, load_config
from .data_inspection import _md_table
from .distance_calculator import haversine_km


def _pct(x: float, d: int = 1) -> str:
    return f"{100 * x:.{d}f}%"


def build_phase2_report(pre, tables: dict) -> str:
    cfg = load_config()
    q = pre.quality_log
    rec = pre.reconciliation
    z = pre.zones
    cv = pre.coord_validation
    rc = tables["regime"].copy()
    stab = tables["stability"]
    sp = tables["sparsity"]
    dest = tables["destination"]
    s = tables["summary"]
    raw_units = int(q.iloc[0]["units_affected"])
    final = q[q["stage"] == "final"].iloc[0]
    zsum = (z.groupby("network").agg(zones=("zone_id", "size"), customers=("n_customers", "sum"),
                                     coordinates=("n_coordinates", "sum"), orders=("n_orders", "sum"),
                                     units=("units", "sum"), median_zone_units=("units", "median"),
                                     max_radius_km=("max_km_from_centroid", "max"))
              .reindex(["CONUS", "Puerto Rico", "Hawaii"]).reset_index())
    dmax = pre.diameters.groupby("network")["max_pairwise_km"].max()
    zsum["max_pairwise_km"] = zsum["network"].map(dmax).round(2)
    zsum["diameter_limit_km"] = zsum["network"].map(cfg["demand_zones"]["max_diameter_km"])

    def metric(scope, name):
        v = s[(s["scope"] == scope) & (s["metric"] == name)]["value"]
        return v.iloc[0] if len(v) else None

    rc_show = rc[["network", "regime", "calendar_days", "orders", "units", "orders_per_day", "units_per_order",
                  "items_per_order", "units_per_item", "customers", "share_customers_seen_before_break",
                  "categories", "top_category"]].copy()
    for c in ["orders_per_day", "units_per_order", "items_per_order", "units_per_item",
              "share_customers_seen_before_break"]:
        rc_show[c] = rc_show[c].round(3)

    qshow = q[["step", "stage", "rule", "action", "records_affected", "orders_affected", "units_affected",
               "orders_remaining_in_demand_set"]].copy()
    hl = tables["high_low"]
    top_conus = hl[(hl["network"] == "CONUS") & (hl["tier"] == "high")][
        ["zone_id", "dominant_city", "dominant_state", "n_customers", "n_orders", "units", "share_of_network_units"]].copy()
    top_conus["share_of_network_units"] = (100 * top_conus["share_of_network_units"]).round(2)
    top_pr = hl[(hl["network"] == "Puerto Rico") & (hl["tier"] == "high")].head(5)[
        ["zone_id", "n_customers", "n_orders", "units", "share_of_network_units", "centroid_lat", "centroid_lon"]].copy()
    top_pr["share_of_network_units"] = (100 * top_pr["share_of_network_units"]).round(2)

    ref = cv[(cv["evidence"] == "reference city centre") & (cv["subject"] != "Caguas, PR")]
    refk = ref["km_median_to_reference"]
    dshare = cv[cv["evidence"] == "domestic destination share (orders)"]["value"]
    conus_pre = rc[(rc.network == "CONUS") & (rc.regime == "pre_2017_10")].iloc[0]
    conus_post = rc[(rc.network == "CONUS") & (rc.regime == "post_2017_10")].iloc[0]
    sp_w = sp.pivot(index="network", columns="granularity", values="zero_share")

    L = [
        "# Phase 2: Cleaning, Demand Zones and Demand Analytics",
        "",
        "_Generated by `python main.py preprocess`. Every number is computed from the data. "
        "Approved scope: CONUS is the primary network, Puerto Rico a separate network, Hawaii is for analysis "
        "only, and international destinations are never routed._",
        "",
        "## 1. Cleaning decisions (`data/outputs/data_quality_report.csv`)",
        "",
        "Rows are **flagged, not deleted**. `cleaned_data.csv` keeps every raw row (minus PII columns), "
        "with `is_demand`, `coord_valid`, `network`, `in_demand_set`, `regime` and `destination_domestic` flags, so "
        "every exclusion can be audited and reversed. The raw CSV is never modified.",
        "",
        _md_table(qshow),
        "",
        f"**Result:** {int(final['orders_affected']):,} orders / {int(final['units_affected']):,} units "
        f"({_pct(final['units_affected'] / raw_units)} of raw units) form the spatial demand set.",
        "",
        "## 2. Coordinate interpretation, validated",
        "",
        "The data dictionary labels `Latitude`/`Longitude` \"location of store\". The tests below show that they "
        "behave as the **customer's location** (city level), which is how this project uses them.",
        "",
        _md_table(cv[cv["evidence"] == "reference city centre"][[
            "subject", "n_customers", "data_median_lat", "data_median_lon", "reference_lat", "reference_lon",
            "km_median_to_reference", "p50_km_customer_to_city_median", "p90_km_customer_to_city_median"]]),
        "",
        f"* For real cities (all except the catch-all Caguas) the median customer coordinate lies "
        f"**{refk.min():.1f} to {refk.max():.1f} km** from the public city centre, "
        f"and the median customer lies {ref['p50_km_customer_to_city_median'].min():.1f}–"
        f"{ref['p50_km_customer_to_city_median'].max():.1f} km from their city's median point. Coordinates are "
        "city-level points, "
        "not exact addresses.",
        "* **Caguas, PR is a catch-all label.** "
        f"{int(cv[cv.subject == 'Caguas, PR']['n_customers'].iloc[0]):,} customers carry it, but their "
        "coordinates spread across the whole island (90th percentile "
        f"{cv[cv.subject == 'Caguas, PR']['p90_km_customer_to_city_median'].iloc[0]} km from the median). "
        "In Puerto Rico the coordinates, not the city name, define location.",
        "* **Destinations are not geographically linked to customers.** Chi-square tests of "
        "`destination_domestic` against customer location:",
        "",
        _md_table(dest.round(4)),
        "",
        f"  Cramér's V = {dest['cramers_v'].min():.3f}–{dest['cramers_v'].max():.3f} is a negligible effect. "
        f"{_pct(dshare.min())}–{_pct(dshare.max())} of orders are \"domestic\" in every network, whatever the "
        "customer's state or network. Real shipping would show a strong dependence, so using customer "
        "coordinates as demand points (approved scope) is the only geographically coherent choice. "
        "Setting `preprocessing.destination_scope: domestic_only` in `config.yaml` restricts demand to the "
        "domestic-destination subset if a stricter reading is wanted.",
        "",
        "## 3. Demand zones",
        "",
        "Validated unique coordinates are clustered per network with **complete-linkage hierarchical clustering** "
        "(chord distance on the unit sphere, cut at the configured diameter). Complete linkage guarantees that "
        "*every pair* of customers in a zone is within the diameter. The exact check below recomputes all "
        "pairwise great-circle distances. The method is deterministic (no random seed).",
        "",
        _md_table(zsum.round(2)),
        "",
        "Zone centroids are **unit-weighted** means of the member coordinates. Zone IDs are ranked by units "
        "within each network. The diameters ("
        + ", ".join(f"{k} {v} km" for k, v in cfg["demand_zones"]["max_diameter_km"].items())
        + ") are modelling choices. "
        f"They keep the CFLP tractable (I = {len(z[z.network == 'CONUS'])} CONUS zones) while staying small relative to inter-city distances.",
        "",
        "Highest-demand CONUS zones:",
        "",
        _md_table(top_conus),
        "",
        f"* CONUS demand is concentrated: {metric('CONUS', 'zones needed for 80% of units')} of "
        f"{len(z[z.network == 'CONUS'])} zones carry 80% of units (Gini {metric('CONUS', 'zone units Gini'):.2f}).",
        f"* Puerto Rico is extremely concentrated: its two largest zones, about "
        f"{haversine_km(top_pr.iloc[0].centroid_lat, top_pr.iloc[0].centroid_lon, top_pr.iloc[1].centroid_lat, top_pr.iloc[1].centroid_lon):.1f} km apart "
        f"near ({top_pr.iloc[0].centroid_lat:.2f}, {top_pr.iloc[0].centroid_lon:.2f}), carry "
        f"{_pct(top_pr['share_of_network_units'].head(2).sum() / 100)} of PR units.",
        "",
        _md_table(top_pr),
        "",
        "## 4. Aggregation validation (`phase2_aggregation_reconciliation.csv`)",
        "",
        "Order-item rows → orders (one delivery each) → zone × day. Units, orders, items and sales are "
        "conserved at every level, and each order, and each customer, maps to exactly one zone:",
        "",
        _md_table(rec.assign(value_a=rec["value_a"].round(2), value_b=rec["value_b"].round(2),
                             passed=rec["passed"].map({True: "PASS", False: "FAIL"}))),
        "",
        f"**{int(rec['passed'].sum())}/{len(rec)} checks pass.** The pipeline raises an error if any fails.",
        "",
        "## 5. Historical demand patterns",
        "",
        "### 5.1 The October 2017 distribution change",
        "",
        _md_table(rc_show),
        "",
        f"* **Orders per day rise** (CONUS {conus_pre.orders_per_day:.1f} → {conus_post.orders_per_day:.1f}), "
        f"but **units per order fall about {conus_pre.units_per_order / conus_post.units_per_order:.1f}x** "
        f"({conus_pre.units_per_order:.2f} → {conus_post.units_per_order:.2f}). Orders become single-item, "
        "single-unit.",
        f"* **The customers are new:** only {_pct(conus_post.share_customers_seen_before_break)} of CONUS customers "
        "ordering from 2017-10 had ordered before.",
        f"* **The product mix is replaced:** top category {conus_pre.top_category} → {conus_post.top_category} "
        "(see `phase2_category_shift.png`).",
        f"* **The spatial pattern is preserved.** Zone order shares before and after correlate with Spearman ρ = "
        f"{stab.set_index('network').loc['CONUS', 'spearman_rho_zone_order_share']:.2f} (CONUS), "
        f"{stab.set_index('network').loc['Puerto Rico', 'spearman_rho_zone_order_share']:.2f} (PR) and "
        f"{stab.set_index('network').loc['Hawaii', 'spearman_rho_zone_order_share']:.2f} (HI).",
        "",
        "**Interpretation:** the break looks like a change of catalogue and customer cohort, not a change in "
        "*where* demand comes from. Two consequences follow:",
        "1. **Unit-based demand cannot be extrapolated across the break.** A model trained on 2015–2017-09 units "
        f"will overshoot post-break units about {conus_pre.units_per_day / conus_post.units_per_day:.1f}x "
        "(CONUS units/day). Forecasting must condition on the regime, or forecast "
        "**orders** (deliveries, which stay stable), or both.",
        "2. **Spatial shares are robust,** so warehouse location (which depends on *where* demand is) is far less "
        "sensitive to the break than total volume is.",
        "",
        "### 5.2 Temporal structure",
        "",
        f"* Monthly unit CV before the break: CONUS {metric('CONUS', 'monthly units CV (pre-break)'):.3f}, "
        f"PR {metric('Puerto Rico', 'monthly units CV (pre-break)'):.3f}. There is **no visible seasonality** "
        "or trend (`phase2_monthly_demand.png`, `phase2_weekly_orders.png`).",
        f"* Weekday index range (max − min) in CONUS before the break: "
        f"{metric('CONUS | pre_2017_10', 'weekday orders index range (max-min)'):.3f}. "
        "There is **no weekday effect** (`phase2_day_of_week.png`).",
        "* Calendar features will therefore add little signal. The honest expectation for Phase 3 is that the "
        "zone's own demand level (lags, rolling means) dominates. XGBoost must be compared with a moving-average "
        "baseline, which may perform similarly.",
        "",
        "### 5.3 Sparsity",
        "",
        _md_table((100 * sp_w[["day", "week", "month"]]).round(1).reset_index().rename(columns={"day": "zero % (zone-day)",
                                                                     "week": "zero % (zone-week)",
                                                                     "month": "zero % (zone-month)"})),
        "",
        "Most zone-days are zero, so daily zone forecasts are not meaningful. Phase 3 will compare **weekly** and "
        "**monthly** zone-level targets (and network-level totals). The CFLP consumes a per-zone demand rate for "
        "the planning horizon.",
        "",
        "## 6. Figures",
        "",
        "| File | Content |", "|---|---|",
        "| `reports/figures/phase2_demand_zones_conus.png` | CONUS zone map (bubble area ∝ units) |",
        "| `reports/figures/phase2_demand_zones_pr_hi.png` | Puerto Rico and Hawaii zone maps |",
        "| `reports/figures/phase2_demand_zones_map.html` | Interactive zone map (Folium; tiles load in the browser) |",
        "| `reports/figures/phase2_monthly_demand.png` | Orders and units per month by network, with the break |",
        "| `reports/figures/phase2_weekly_orders.png` | Weekly orders with 4-week rolling mean |",
        "| `reports/figures/phase2_day_of_week.png` | Weekday index (flat) |",
        "| `reports/figures/phase2_category_shift.png` | Category mix before vs after the break |",
        "| `reports/figures/phase2_regime_comparison.png` | Orders/day, units/order, items/order, units/day |",
        "| `reports/figures/phase2_zone_concentration.png` | Pareto curve of zone demand |",
        "| `reports/figures/phase2_zone_spatial_stability.png` | Zone shares before vs after the break |",
        "| `reports/figures/phase2_demand_sparsity.png` | Zero-demand share by time granularity |",
        "",
        "## 7. Privacy",
        "",
        "`Customer Fname`, `Customer Lname`, `Customer Street`, `Customer Email`, `Customer Password` and "
        "`Customer Zipcode` are removed before any file is written. `_assert_no_pii` blocks a write if a PII "
        "column reappears, and a unit test checks the written files. `customer_id` is the dataset's pseudonymous "
        "key. Coordinates are city-level points (see §2), not street addresses. Processed files stay git-ignored. "
        "Only aggregated zone-level tables are committed.",
        "",
        "## 8. Outputs",
        "",
        "| File | Grain | Committed |", "|---|---|---|",
        "| `data/processed/cleaned_data.csv` | order item (all raw rows, PII removed, flags added) | no (regenerate) |",
        "| `data/processed/orders.csv` | order = delivery | no |",
        "| `data/processed/zone_daily_demand.csv` | zone × day, zero-filled | no |",
        "| `data/processed/network_category_daily_demand.csv` | network × category × day | no |",
        "| `data/processed/demand_zones.csv` / `data/outputs/demand_zones.csv` | zone | outputs copy: yes |",
        "| `data/outputs/data_quality_report.csv` | cleaning decision | yes |",
        "| `data/outputs/eda_summary.csv` | metric | yes |",
        "| `data/outputs/eda_*.csv`, `phase2_*.csv` | analysis tables | yes |",
        "",
    ]
    return "\n".join(L)


def write_phase2_report(pre, tables: dict) -> None:
    path = get_path("reports_dir") / "phase2_preprocessing_eda.md"
    path.write_text(build_phase2_report(pre, tables), encoding="utf-8")
